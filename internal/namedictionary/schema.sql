-- Dictionary content is installed exactly once, in the same migration transaction.
CREATE TABLE IF NOT EXISTS name_dictionary_state (
 key text PRIMARY KEY, next_value bigint NOT NULL DEFAULT 0 CHECK(next_value>=0),
 initialized_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
COMMENT ON TABLE name_dictionary_state IS 'Однократное наполнение и курсоры генерации названий';
COMMENT ON COLUMN name_dictionary_state.key IS 'Имя словаря или операции начального наполнения';
COMMENT ON COLUMN name_dictionary_state.next_value IS 'Следующий порядковый номер для уникального названия';
COMMENT ON COLUMN name_dictionary_state.initialized_at IS 'Время первоначального создания записи';
CREATE TABLE IF NOT EXISTS system_names (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 word text NOT NULL CHECK(char_length(btrim(word)) BETWEEN 1 AND 100),
 part text NOT NULL CHECK(part IN('base','suffix')),
 active boolean NOT NULL DEFAULT true,
 UNIQUE(word,part)
);
COMMENT ON TABLE system_names IS 'Редактируемый словарь названий: system_names';
COMMENT ON COLUMN system_names.id IS 'Постоянный идентификатор слова';
COMMENT ON COLUMN system_names.word IS 'Слово или фамилия для генерации названия';
COMMENT ON COLUMN system_names.part IS 'Часть названия: основа или окончание';
COMMENT ON COLUMN system_names.active IS 'Разрешено ли использовать слово в новых названиях';
