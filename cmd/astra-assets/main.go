// astra-assets prepares the external graphics package and browser hash resolver.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"github.com/yomezza/cosmosimulator/internal/assetpack"
	"os"
	"regexp"
)

func main() {
	root := flag.String("root", "assets/game", "source graphics")
	out := flag.String("out", "downloads", "archive destination")
	tag := flag.String("tag", "v0.29.0", "release tag")
	client := flag.String("client", "internal/server/web/core/generated-assets.js", "browser URL table; empty disables writing")
	check := flag.Bool("check", false, "check generated browser/HTML references without changing them")
	flag.Parse()
	release, urls, err := assetpack.Build(*root, *out, *tag)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *client != "" {
		raw, _ := json.MarshalIndent(urls, "", "  ")
		body := "// Generated by cmd/astra-assets; public metadata only, no image bytes.\nexport const ASSET_URLS = " + string(raw) + ";\n"
		if *check {
			old, e := os.ReadFile(*client)
			if e != nil || !bytes.Equal(old, []byte(body)) {
				fmt.Fprintln(os.Stderr, "public asset URL table is stale; run go run ./cmd/astra-assets")
				os.Exit(1)
			}
		} else if err = os.WriteFile(*client, []byte(body), 0644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		index := "internal/server/web/index.html"
		html, e := os.ReadFile(index)
		if e != nil {
			fmt.Fprintln(os.Stderr, e)
			os.Exit(1)
		}
		re := regexp.MustCompile(`data-asset="([^"]+)" href="[^"]*"`)
		updated := re.ReplaceAllStringFunc(string(html), func(s string) string {
			m := re.FindStringSubmatch(s)
			suffix := ""
			if m[1] != "/favicon.svg" {
				suffix = "#icon"
			}
			return `data-asset="` + m[1] + `" href="` + urls[m[1]] + suffix + `"`
		})
		if *check && updated != string(html) {
			fmt.Fprintln(os.Stderr, "HTML asset references are stale")
			os.Exit(1)
		}
		if !*check {
			if e = os.WriteFile(index, []byte(updated), 0644); e != nil {
				fmt.Fprintln(os.Stderr, e)
				os.Exit(1)
			}
		}
	}
	fmt.Printf("Asset pack %s (%d bytes)\n", release.Revision, release.Size)
}
